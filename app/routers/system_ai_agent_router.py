from __future__ import annotations

import logging
import os
import uuid
from typing import Set

from fastapi import APIRouter, HTTPException, Request, Response
from pydantic import BaseModel, Field

from ..crud.system_ai_agent_crud import (
    RateLimitedError,
    SystemAIUnavailableError,
    system_chat,
    end_session,
    MAX_INPUT_CHARS,
)

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/system-ai", tags=["System AI (YOUR_APP Assistant)"])

_TRUSTED_PROXY_IPS: Set[str] = {
    ip.strip()
    for ip in os.environ.get("TRUSTED_PROXY_IPS", "").split(",")
    if ip.strip()
}


def _get_client_ip(request: Request) -> str:
    direct_ip = request.client.host if request.client else "unknown"
    if direct_ip in _TRUSTED_PROXY_IPS:
        forwarded = request.headers.get("X-Forwarded-For", "")
        if forwarded:
            return forwarded.split(",")[0].strip()
    return direct_ip


class SystemChatRequest(BaseModel):
    question: str = Field(
        ...,
        min_length=1,
        max_length=MAX_INPUT_CHARS,
        description="User's question (plain text).",
    )
    session_id: str = Field(
        ...,
        min_length=36,
        max_length=36,
        description="UUID v4 generated by the frontend on widget mount. Identifies the conversation.",
    )


class EndSessionRequest(BaseModel):
    session_id: str = Field(
        ...,
        min_length=36,
        max_length=36,
        description="UUID v4 of the session to wipe from memory.",
    )


class SystemChatResponse(BaseModel):
    answer: str


@router.post(
    "/chat",
    response_model=SystemChatResponse,
    summary="YOUR_APP company AI assistant — public, no auth required",
    description=(
        "Send a question along with a client-generated session_id (UUID v4). "
        "The server keeps the last 10 turns of that session in memory. "
        "Rate limited to 20 req/min and 200 req/day per IP."
    ),
)
async def system_ai_chat(
    body: SystemChatRequest,
    request: Request,
) -> SystemChatResponse:
    client_ip = _get_client_ip(request)

    try:
        session_id = str(uuid.UUID(body.session_id))
    except ValueError:
        raise HTTPException(status_code=422, detail="session_id must be a valid UUID v4.")

    try:
        answer = await system_chat(body.question, client_ip, session_id)

    except ValueError as exc:
        raise HTTPException(status_code=422, detail=str(exc))

    except RateLimitedError as exc:
        window = str(exc)
        retry = 60 if window == "minute" else 3600
        raise HTTPException(
            status_code=429,
            detail=(
                "You're sending messages too quickly — please wait a moment."
                if window == "minute"
                else "Daily message limit reached. Please try again tomorrow."
            ),
            headers={"Retry-After": str(retry)},
        )

    except SystemAIUnavailableError:
        raise HTTPException(
            status_code=503,
            detail="AI assistant is temporarily unavailable. Please try again shortly.",
            headers={"Retry-After": "30"},
        )

    except Exception as exc:
        logger.error("system_ai_chat: unhandled error ip=%s: %s", client_ip, exc, exc_info=True)
        raise HTTPException(status_code=500, detail="Unexpected error.")

    return SystemChatResponse(answer=answer)


@router.post(
    "/chat/end",
    status_code=204,
    response_model=None,
    summary="Wipe a session from memory when the user closes the chat widget",
)
async def system_ai_end_session(
    body: EndSessionRequest,
    request: Request,
) -> None:
    try:
        session_id = str(uuid.UUID(body.session_id))
        await end_session(session_id)
    except ValueError:
        pass